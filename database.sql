CREATE TYPE enum_mascotas_sexo AS ENUM ('MACHO', 'HEMBRA', 'NO_ESPECIFICADO');
CREATE TYPE enum_citas_estado AS ENUM ('PROGRAMADA', 'CONFIRMADA', 'ATENDIDA', 'CANCELADA');

CREATE TABLE clientes (
  id SERIAL PRIMARY KEY,
  nombre VARCHAR(120) NOT NULL,
  identificacion VARCHAR(30) NOT NULL UNIQUE,
  telefono VARCHAR(30) NOT NULL,
  correo VARCHAR(150) NOT NULL UNIQUE,
  direccion VARCHAR(200),
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW()
);

CREATE TABLE veterinarios (
  id SERIAL PRIMARY KEY,
  nombre VARCHAR(120) NOT NULL,
  registro_profesional VARCHAR(40) NOT NULL UNIQUE,
  especialidad VARCHAR(100) NOT NULL,
  telefono VARCHAR(30) NOT NULL,
  correo VARCHAR(150) NOT NULL UNIQUE,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW()
);

CREATE TABLE mascotas (
  id SERIAL PRIMARY KEY,
  nombre VARCHAR(100) NOT NULL,
  especie VARCHAR(60) NOT NULL,
  raza VARCHAR(100),
  fecha_nacimiento DATE,
  sexo enum_mascotas_sexo NOT NULL,
  cliente_id INTEGER NOT NULL REFERENCES clientes(id) ON DELETE RESTRICT ON UPDATE CASCADE,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW()
);

CREATE TABLE citas (
  id SERIAL PRIMARY KEY,
  fecha_hora TIMESTAMP WITH TIME ZONE NOT NULL,
  motivo VARCHAR(500) NOT NULL,
  estado enum_citas_estado NOT NULL DEFAULT 'PROGRAMADA',
  mascota_id INTEGER NOT NULL REFERENCES mascotas(id) ON DELETE RESTRICT ON UPDATE CASCADE,
  veterinario_id INTEGER NOT NULL REFERENCES veterinarios(id) ON DELETE RESTRICT ON UPDATE CASCADE,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW()
);

CREATE TABLE historias_clinicas (
  id SERIAL PRIMARY KEY,
  fecha DATE NOT NULL,
  diagnostico TEXT NOT NULL,
  tratamiento TEXT NOT NULL,
  observaciones TEXT,
  mascota_id INTEGER NOT NULL REFERENCES mascotas(id) ON DELETE RESTRICT ON UPDATE CASCADE,
  veterinario_id INTEGER NOT NULL REFERENCES veterinarios(id) ON DELETE RESTRICT ON UPDATE CASCADE,
  cita_id INTEGER UNIQUE REFERENCES citas(id) ON DELETE SET NULL ON UPDATE CASCADE,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW()
);